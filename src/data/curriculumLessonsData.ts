// ============================================================================
// Deterministic Structured Narration & Alignment Builders (All 27 Lessons)
// Guarantees 100% full-page reading without skipping any paragraph/equation/tip
// AND guarantees math tokens NEVER highlight while Arabic rule words are read.
// ============================================================================

export interface CustomNarrationSlot {
  secIndex: number; // -1 for intro / closing
  subPart: 'intro' | 'title' | 'rule' | 'math' | 'exampleProblem' | 'exampleSolution' | 'tip' | 'closing';
  mathPartIdx?: number;
  wordStart?: number;
  wordEnd?: number;
}

export interface CustomPageNarrationTimeline {
  sentences: string[];
  slots: CustomNarrationSlot[];
}

function appendAlignedTextSegments(
  sentences: string[],
  pushSlot: (wordStart?: number, wordEnd?: number) => void,
  rawText: string,
  spokenPrefix: string = ''
) {
  const cleanRaw = (rawText || '').trim();
  if (!cleanRaw) return;

  const words = cleanRaw.split(/\s+/).filter(Boolean);
  const subSentences = normalizeAndSplitSpeechSentences(cleanRaw);

  if (subSentences.length === 0) {
    const fallback = normalizeAndSplitSpeechSentences(spokenPrefix ? `${spokenPrefix} ${cleanRaw}` : cleanRaw);
    fallback.forEach((s) => {
      sentences.push(s);
      pushSlot(0, words.length);
    });
    return;
  }

  const totalChars = Math.max(1, subSentences.reduce((sum, s) => sum + s.length, 0));
  let cumChars = 0;

  subSentences.forEach((sub, idx) => {
    const wStart = words.length > 0 ? Math.min(words.length - 1, Math.round((cumChars / totalChars) * words.length)) : 0;
    cumChars += sub.length;
    const isLast = idx === subSentences.length - 1;
    const wEnd = words.length > 0
      ? (isLast ? words.length : Math.max(wStart + 1, Math.min(words.length, Math.round((cumChars / totalChars) * words.length))))
      : 0;

    const cleanPrefix = idx === 0 && spokenPrefix.trim()
      ? `${normalizeAndSplitSpeechSentences(spokenPrefix).join(' ')} `
      : '';
    sentences.push(`${cleanPrefix}${sub}`.trim());
    pushSlot(wStart, wEnd);
  });
}

export function buildCustomPageNarrationTimeline(page: BookPageData): CustomPageNarrationTimeline {
  const sentences: string[] = [];
  const slots: CustomNarrationSlot[] = [];

  if (!page) return { sentences, slots };

  // 1. Page Title + Objective (strictly highlights objective box only)
  const introTitleParts = normalizeAndSplitSpeechSentences(`${page.pageTitle}، صفحة ${page.pageNum}.`);
  introTitleParts.forEach((s) => {
    sentences.push(s);
    slots.push({ secIndex: -1, subPart: 'intro' });
  });

  if (page.objective) {
    appendAlignedTextSegments(
      sentences,
      (wordStart, wordEnd) => slots.push({ secIndex: -1, subPart: 'intro', wordStart, wordEnd }),
      page.objective,
      'الهدف التعليمي للصفحة:'
    );
  }

  // 2. Every section on the page: Title -> Rule -> Math Equation(s) -> Example Problem -> Example Solution -> Key Tip
  page.sections.forEach((sec, sIdx) => {
    // Title
    appendAlignedTextSegments(
      sentences,
      (wordStart, wordEnd) => slots.push({ secIndex: sIdx, subPart: 'title', wordStart, wordEnd }),
      sec.title
    );

    // Rule Text (Arabic explanation ONLY — math box does NOT highlight here!)
    if (sec.ruleText) {
      appendAlignedTextSegments(
        sentences,
        (wordStart, wordEnd) => slots.push({ secIndex: sIdx, subPart: 'rule', wordStart, wordEnd }),
        sec.ruleText
      );
    }

    // Math Equation(s) split by '|' so each formula illuminates ONLY when that formula is spoken
    if (sec.mathEquation) {
      const eqParts = sec.mathEquation.split('|').map(p => p.trim()).filter(Boolean);
      eqParts.forEach((eqPart, eqIdx) => {
        const prefix = eqIdx === 0 ? 'العلاقة الرياضية هي ' : 'وكذلك العلاقة ';
        const eqSentences = normalizeAndSplitSpeechSentences(`${prefix} ${eqPart}`);
        eqSentences.forEach((s) => {
          sentences.push(s);
          slots.push({ secIndex: sIdx, subPart: 'math', mathPartIdx: eqIdx });
        });
      });
    }

    // Example Problem
    if (sec.exampleProblem) {
      appendAlignedTextSegments(
        sentences,
        (wordStart, wordEnd) => slots.push({ secIndex: sIdx, subPart: 'exampleProblem', wordStart, wordEnd }),
        sec.exampleProblem,
        'مثال تطبيقي'
      );
    }

    // Example Solution
    if (sec.exampleSolution) {
      appendAlignedTextSegments(
        sentences,
        (wordStart, wordEnd) => slots.push({ secIndex: sIdx, subPart: 'exampleSolution', wordStart, wordEnd }),
        sec.exampleSolution,
        'الحل'
      );
    }

    // Key Tip
    if (sec.keyTip) {
      appendAlignedTextSegments(
        sentences,
        (wordStart, wordEnd) => slots.push({ secIndex: sIdx, subPart: 'tip', wordStart, wordEnd }),
        sec.keyTip,
        'ملاحظة مهمة'
      );
    }
  });

  // 3. Closing line
  const closingParts = normalizeAndSplitSpeechSentences(
    page.summaryNote ? page.summaryNote : `بذلك يكتمل شرح الصفحة ${page.pageNum} بالكامل.`
  );
  closingParts.forEach((s) => {
    sentences.push(s);
    slots.push({ secIndex: -1, subPart: 'closing' });
  });

  return { sentences, slots };
}

export interface CustomBoardNarrationSlot {
  lineIdx: number; // -1 for closing
  isMath: boolean;
  mathPartIdx?: number;
  wordStart?: number;
  wordEnd?: number;
}

export interface CustomBoardNarrationTimeline {
  sentences: string[];
  slots: CustomBoardNarrationSlot[];
}

export function buildCustomBoardNarrationTimeline(page: BoardFullPage): CustomBoardNarrationTimeline {
  const sentences: string[] = [];
  const slots: CustomBoardNarrationSlot[] = [];

  if (!page) return { sentences, slots };

  page.boardLines.forEach((line, lineIdx) => {
    if (line.type === 'divider') return;

    const rawEq = (line.equation || '').trim();
    const rawTxt = (line.text || '').trim();

    if (line.equation || line.type === 'result') {
      const targetStr = rawEq || rawTxt;
      if (!targetStr) return;

      const labelPrefix = line.label ? `${line.label} ` : '';
      const eqParts = targetStr.split('|').map(p => p.trim()).filter(Boolean);
      eqParts.forEach((eqPart, partIdx) => {
        const prefix = partIdx === 0 ? labelPrefix : 'وكذلك ';
        const eqSentences = normalizeAndSplitSpeechSentences(`${prefix} ${eqPart}`);
        eqSentences.forEach((s) => {
          sentences.push(s);
          slots.push({ lineIdx, isMath: true, mathPartIdx: partIdx });
        });
      });
      return;
    }

    if (!rawTxt) return;

    const colonIdx = rawTxt.indexOf(':');
    const isMixedMath =
      line.type === 'math' &&
      (rawTxt.includes('/') || rawTxt.includes('=') || rawTxt.includes('+') || rawTxt.includes('-'));

    if (isMixedMath) {
      const mathFormula = colonIdx > 0 ? rawTxt.slice(colonIdx + 1).trim() : rawTxt;
      const labelPrefix = colonIdx > 0 ? rawTxt.slice(0, colonIdx).trim() : '';
      const eqParts = mathFormula.split('|').map(p => p.trim()).filter(Boolean);
      eqParts.forEach((eqPart, partIdx) => {
        const prefix = partIdx === 0 && labelPrefix ? `${labelPrefix} ` : partIdx > 0 ? 'وكذلك ' : '';
        const eqSentences = normalizeAndSplitSpeechSentences(`${prefix} ${eqPart}`);
        eqSentences.forEach((s) => {
          sentences.push(s);
          slots.push({ lineIdx, isMath: true, mathPartIdx: partIdx });
        });
      });
      return;
    }

    // Text line (header, title, rule, example, note)
    appendAlignedTextSegments(
      sentences,
      (wordStart, wordEnd) => slots.push({ lineIdx, isMath: false, wordStart, wordEnd }),
      rawTxt
    );
  });

  const closing = normalizeAndSplitSpeechSentences(`وبهذا يكتمل شرح الصفحة ${page.bookPageNum} على السبورة.`);
  closing.forEach((s) => {
    sentences.push(s);
    slots.push({ lineIdx: -1, isMath: false });
  });

  return { sentences, slots };
}

export interface CurriculumSummarySlot {
  part: 'overview' | 'ruleText' | 'ruleEquation' | 'exampleProblem' | 'exampleSolution';
  mathPartIdx?: number;
  wordStart?: number;
  wordEnd?: number;
}

export interface CurriculumSummaryNarrationTimeline {
  sentences: string[];
  slots: CurriculumSummarySlot[];
}

export function buildCurriculumSummaryNarrationTimeline(lesson: CurriculumLesson): CurriculumSummaryNarrationTimeline {
  const sentences: string[] = [];
  const slots: CurriculumSummarySlot[] = [];

  if (!lesson) return { sentences, slots };

  normalizeAndSplitSpeechSentences(`${lesson.title}. ${lesson.subtitle}.`).forEach((s) => {
    sentences.push(s);
    slots.push({ part: 'overview' });
  });

  appendAlignedTextSegments(
    sentences,
    (wordStart, wordEnd) => slots.push({ part: 'overview', wordStart, wordEnd }),
    lesson.summary,
    'ملخص الدرس'
  );

  appendAlignedTextSegments(
    sentences,
    (wordStart, wordEnd) => slots.push({ part: 'ruleText', wordStart, wordEnd }),
    lesson.keyRule,
    'القاعدة الجوهرية'
  );

  if (lesson.ruleEquation) {
    const eqParts = lesson.ruleEquation.split('|').map(p => p.trim()).filter(Boolean);
    eqParts.forEach((eqPart, eqIdx) => {
      const prefix = eqIdx === 0 ? 'القانون الرياضي هو ' : 'وكذلك ';
      normalizeAndSplitSpeechSentences(`${prefix} ${eqPart}`).forEach((s) => {
        sentences.push(s);
        slots.push({ part: 'ruleEquation', mathPartIdx: eqIdx });
      });
    });
  }

  appendAlignedTextSegments(
    sentences,
    (wordStart, wordEnd) => slots.push({ part: 'exampleProblem', wordStart, wordEnd }),
    lesson.exampleProblem,
    'مثال تطبيقي'
  );

  appendAlignedTextSegments(
    sentences,
    (wordStart, wordEnd) => slots.push({ part: 'exampleSolution', wordStart, wordEnd }),
    lesson.exampleSolution,
    'خطوات الحل'
  );

  return { sentences, slots };
}

